import * as fs from 'node:fs';
import * as path from 'node:path';
import { generateHmacSecret, generateRsaKeyPair } from '@nullfilter/core';

export interface InitCommandResult {
  envFilePath: string;
  publicKeyPem: string;
  privateKeyPem: string;
  hmacSecret: string;
}

/**
 * Generates an RSA-2048 SPKI/PKCS8 keypair and 256-bit HMAC secret, writes them
 * into `.env.originlock`, and prints ready-to-use server integration code.
 */
export function runInitCommand(targetDir = process.cwd()): InitCommandResult {
  const { publicKeyPem, privateKeyPem } = generateRsaKeyPair();
  const hmacSecret = generateHmacSecret(32);

  const escapedPub = publicKeyPem.trim().replace(/\r?\n/g, '\\n');
  const escapedPriv = privateKeyPem.trim().replace(/\r?\n/g, '\\n');

  const envContent = [
    '# Generated by NullFilter / OriginLock CLI',
    `# Timestamp: ${new Date().toISOString()}`,
    '',
    `ORIGINLOCK_PUBLIC_KEY_PEM="${escapedPub}"`,
    `ORIGINLOCK_PRIVATE_KEY_PEM="${escapedPriv}"`,
    `ORIGINLOCK_HMAC_SECRET="${hmacSecret}"`,
    'ORIGINLOCK_ALLOWED_HOSTNAMES="quellcloud.com,localhost"',
    'ORIGINLOCK_ALLOWED_ORIGINS="https://quellcloud.com,http://localhost:3000"',
    'ORIGINLOCK_ENABLE_HONEYPOT="true"',
    '',
  ].join('\n');

  const envFilePath = path.resolve(targetDir, '.env.originlock');
  fs.writeFileSync(envFilePath, envContent, { encoding: 'utf8', mode: 0o600 });

  const green = '\x1b[32m';
  const cyan = '\x1b[36m';
  const yellow = '\x1b[33m';
  const bold = '\x1b[1m';
  const reset = '\x1b[0m';

  console.log(`\n${bold}${green}✔ RSA-2048 OAEP Keypair & 256-bit HMAC Secret Provisioned${reset}`);
  console.log(`${cyan}  Configuration written to:${reset} ${envFilePath}\n`);
  console.log(`${yellow}Quickstart Server Integration:${reset}`);
  console.log(`
  import { OriginLockShield } from '@nullfilter/server';

  const shield = new OriginLockShield({
    publicKeyPem: process.env.ORIGINLOCK_PUBLIC_KEY_PEM!.replace(/\\\\n/g, '\\n'),
    privateKeyPem: process.env.ORIGINLOCK_PRIVATE_KEY_PEM!.replace(/\\\\n/g, '\\n'),
    hmacSecret: process.env.ORIGINLOCK_HMAC_SECRET!,
    allowedHostnames: ['quellcloud.com'],
    allowedOrigins: ['https://quellcloud.com'],
    enableHoneypotPoisoning: true,
  });
`);

  return {
    envFilePath,
    publicKeyPem,
    privateKeyPem,
    hmacSecret,
  };
}
